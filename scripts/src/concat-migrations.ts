/**
 * Concatenates all SQL files in artifacts/punterstat/supabase/migrations
 * in numeric order into scripts/all_migrations.sql (or stdout when --stdout is passed).
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const migrationsDir = path.resolve(
  __dirname,
  "../../artifacts/punterstat/supabase/migrations",
);
const defaultOutput = path.resolve(__dirname, "../all_migrations.sql");

const files = fs
  .readdirSync(migrationsDir)
  .filter((f) => f.endsWith(".sql"))
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

const chunks: string[] = [
  "-- Auto-generated by scripts/src/concat-migrations.ts — do not edit or commit.",
  "",
];

for (const file of files) {
  const fullPath = path.join(migrationsDir, file);
  const sql = fs.readFileSync(fullPath, "utf8").trimEnd();
  chunks.push(`-- ============================================================`);
  chunks.push(`-- File: ${file}`);
  chunks.push(`-- ============================================================`);
  chunks.push(sql);
  chunks.push("");
}

const combined = chunks.join("\n");

if (process.argv.includes("--stdout")) {
  process.stdout.write(combined);
} else {
  fs.writeFileSync(defaultOutput, combined, "utf8");
  process.stderr.write(
    `Concatenated ${files.length} migrations into ${defaultOutput}\n`,
  );
}
